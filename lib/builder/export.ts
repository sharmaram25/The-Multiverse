import { escapeHtml, renderSection, SITE_CSS, themeVariables } from './render';
import { getSectionDef, isSectionType } from './sections';
import type { BuilderComponent, BuilderProject, SiteTheme } from './types';
import { normalizeHex } from '@/lib/color';
import { FONT_STACKS } from '@/lib/tokens-export';

const GOOGLE_FONTS: Record<string, string> = {
  Inter: 'Inter:wght@400;500;600;700;800',
  'Space Grotesk': 'Space+Grotesk:wght@400;500;600;700',
};

function varsToCss(theme: SiteTheme): string {
  return Object.entries(themeVariables(theme)).map(([k, v]) => `  ${k}: ${v};`).join('\n');
}

export function renderSectionsHtml(sections: BuilderComponent[]): string {
  return sections.map(renderSection).join('\n');
}

/** A complete, dependency-free HTML document. Opens offline; deploys anywhere. */
export function exportHtml(project: BuilderProject): string {
  const font = GOOGLE_FONTS[project.theme.fontFamily];
  const fontLink = font
    ? `  <link rel="preconnect" href="https://fonts.googleapis.com" />\n  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />\n  <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=${font}&display=swap" />\n`
    : '';
  const hero = project.sections.find((s) => s.type === 'hero');
  const fallbackDescription = hero && typeof hero.props.subtitle === 'string' ? hero.props.subtitle : `${project.name} website`;
  const title = project.seo?.title?.trim() || project.name;
  const description = project.seo?.description?.trim() || fallbackDescription;
  const lang = /^[a-z]{2}(-[A-Z]{2})?$/.test(project.seo?.lang ?? '') ? project.seo!.lang! : 'en';
  const ogImage = /^https:\/\//.test(project.seo?.ogImage ?? '') ? project.seo!.ogImage! : '';
  return `<!doctype html>
<html lang="${lang}">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>${escapeHtml(title)}</title>
  <meta name="description" content="${escapeHtml(description.slice(0, 160))}" />
  <meta property="og:title" content="${escapeHtml(title)}" />
  <meta property="og:description" content="${escapeHtml(description.slice(0, 200))}" />
  <meta property="og:type" content="website" />
${ogImage ? `  <meta property="og:image" content="${escapeHtml(ogImage)}" />\n  <meta name="twitter:card" content="summary_large_image" />\n` : ''}
  <meta name="theme-color" content="${normalizeHex(project.theme.primary) ?? '#4f46e5'}" />
  <meta name="generator" content="The Multiverse Builder" />
${fontLink}  <style>
html,body{margin:0;padding:0}
.mv-site{
${varsToCss(project.theme)}
  min-height:100vh;
}
${SITE_CSS.trim()}
  </style>
</head>
<body>
<div class="mv-site">
${renderSectionsHtml(project.sections)}
</div>
</body>
</html>
`;
}

/** Converts our controlled markup to JSX. Safe because renderSection only emits known tags. */
function htmlToJsx(html: string): string {
  return html
    .replace(/\sclass="/g, ' className="')
    .replace(/\sfor="/g, ' htmlFor="')
    .replace(/\sautocomplete="/g, ' autoComplete="')
    // Inline handlers are only meaningful in the static HTML export.
    .replace(/\son[a-z]+="[^"]*"/g, '')
    .replace(/&ldquo;/g, '“')
    .replace(/&rdquo;/g, '”')
    .replace(/\{/g, '&#123;')
    .replace(/\}/g, '&#125;');
}

/** A React (TSX) component plus its stylesheet, ready to drop into Next.js, Vite or Remix. */
export function exportReact(project: BuilderProject): { component: string; css: string } {
  const name = project.name.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c: string | undefined) => (c ? c.toUpperCase() : '')).replace(/^[^a-zA-Z]+/, '');
  const componentName = (name.charAt(0).toUpperCase() + name.slice(1)) || 'LandingPage';
  const body = project.sections.map((s) => `      ${htmlToJsx(renderSection(s))}`).join('\n');
  const component = `// Generated by The Multiverse Builder
import './site.css';

export default function ${componentName}() {
  return (
    <div className="mv-site">
${body}
    </div>
  );
}
`;
  const css = `/* Generated by The Multiverse Builder */
.mv-site {
${varsToCss(project.theme)}
}
${SITE_CSS.trim()}
`;
  return { component, css };
}

export interface BlueprintV2 {
  format: 'multiverse-blueprint';
  version: 2;
  exportedAt: string;
  name: string;
  theme: SiteTheme;
  notes?: string;
  seo?: BuilderProject['seo'];
  sections: Array<{ type: string; props: Record<string, unknown> }>;
}

export function exportBlueprint(project: BuilderProject): string {
  const doc: BlueprintV2 = {
    format: 'multiverse-blueprint',
    version: 2,
    exportedAt: new Date().toISOString(),
    name: project.name,
    theme: project.theme,
    notes: project.notes,
    seo: project.seo,
    sections: project.sections.map(({ type, props }) => ({ type, props })),
  };
  return JSON.stringify(doc, null, 2);
}

export function exportBrief(project: BuilderProject, extra?: { playbook?: { label: string; focus: string; recommendedUniverse: string; routes: string[]; kpis: string[] } }): string {
  const lines: string[] = [`# ${project.name} — Website Planning Brief`, '', `_Generated ${new Date().toLocaleDateString()} with The Multiverse Builder_`, ''];
  if (extra?.playbook) {
    const pb = extra.playbook;
    lines.push('## Strategy', `- **Playbook:** ${pb.label}`, `- **Focus:** ${pb.focus}`, `- **Recommended universe:** ${pb.recommendedUniverse}`, '', '## Route stack', ...pb.routes.map((r) => `- \`${r}\``), '', '## Primary KPIs', ...pb.kpis.map((k) => `- ${k}`), '');
  }
  lines.push('## Visual tokens', `- Primary: \`${project.theme.primary}\``, `- Accent: \`${project.theme.accent}\``, `- Background: \`${project.theme.background}\``, `- Foreground: \`${project.theme.foreground}\``, `- Radius: ${project.theme.radius}px`, `- Font: ${project.theme.fontFamily}`, '');
  lines.push('## Page outline');
  if (project.sections.length === 0) lines.push('- _(empty)_');
  project.sections.forEach((s, i) => {
    const def = getSectionDef(s.type);
    const headline = ['title', 'heading', 'brand', 'quote', 'text', 'content'].map((k) => s.props[k]).find((v) => typeof v === 'string' && v) as string | undefined;
    lines.push(`${i + 1}. **${def?.label ?? s.type}**${headline ? ` — ${headline.slice(0, 90)}` : ''}`);
  });
  if (project.notes?.trim()) lines.push('', '## Notes', project.notes.trim());
  return lines.join('\n') + '\n';
}

// ---------------------------------------------------------------------------
// Import — accepts v2 blueprints and legacy v1 exports. Everything is validated.
// ---------------------------------------------------------------------------

export interface ImportResult {
  name?: string;
  theme?: Partial<SiteTheme>;
  notes?: string;
  seo?: BuilderProject['seo'];
  sections: Array<{ type: BuilderComponent['type']; props: Record<string, unknown> }>;
  skipped: number;
}

function cleanProps(input: unknown): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  if (!input || typeof input !== 'object') return out;
  for (const [k, v] of Object.entries(input as Record<string, unknown>)) {
    if (/^[a-zA-Z][a-zA-Z0-9]{0,40}$/.test(k) && (typeof v === 'string' || typeof v === 'number' || typeof v === 'boolean')) {
      out[k] = typeof v === 'string' ? v.slice(0, 5000) : v;
    }
  }
  return out;
}

export function parseBlueprint(text: string): ImportResult {
  let data: unknown;
  try {
    data = JSON.parse(text);
  } catch {
    throw new Error('This file is not valid JSON.');
  }
  if (!data || typeof data !== 'object' || !Array.isArray((data as { sections?: unknown }).sections)) {
    throw new Error('No "sections" array found — is this a Multiverse blueprint?');
  }
  const doc = data as Record<string, unknown> & { sections: unknown[] };
  let skipped = 0;
  const sections: ImportResult['sections'] = [];
  for (const raw of doc.sections.slice(0, 200)) {
    const type = (raw as { type?: unknown })?.type;
    if (!isSectionType(type)) { skipped++; continue; }
    const def = getSectionDef(type);
    sections.push({ type, props: { ...(def?.defaultProps ?? {}), ...cleanProps((raw as { props?: unknown }).props) } });
  }

  const result: ImportResult = { sections, skipped };
  if (typeof doc.name === 'string') result.name = doc.name.slice(0, 120);
  if (typeof doc.notes === 'string') result.notes = doc.notes.slice(0, 20000);
  if (doc.seo && typeof doc.seo === 'object') {
    const s = doc.seo as Record<string, unknown>;
    const pickStr = (k: string, max: number) => (typeof s[k] === 'string' ? (s[k] as string).slice(0, max) : undefined);
    result.seo = { title: pickStr('title', 120), description: pickStr('description', 320), ogImage: pickStr('ogImage', 500), lang: pickStr('lang', 5) };
  }
  if (doc.theme && typeof doc.theme === 'object') {
    const t = doc.theme as Record<string, unknown>;
    const theme: Partial<SiteTheme> = {};
    for (const key of ['primary', 'accent', 'background', 'foreground'] as const) {
      const hex = typeof t[key] === 'string' ? normalizeHex(t[key] as string) : null;
      if (hex) theme[key] = hex;
    }
    if (typeof t.radius === 'number' && Number.isFinite(t.radius)) theme.radius = Math.max(0, Math.min(48, t.radius));
    if (typeof t.headingScale === 'number' && Number.isFinite(t.headingScale)) theme.headingScale = Math.max(1, Math.min(2, t.headingScale));
    if (typeof t.fontFamily === 'string' && t.fontFamily in FONT_STACKS) theme.fontFamily = t.fontFamily;
    result.theme = theme;
  }
  return result;
}
