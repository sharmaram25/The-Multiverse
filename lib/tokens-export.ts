/**
 * Design-token exporters and share-link encoding.
 * Every exporter is a pure function of the token snapshot, so output is
 * deterministic and identical across devices.
 */
import { normalizeHex, readableOn, tonalScale } from '@/lib/color';

/** The portable subset of design tokens that is exported and shared. */
export interface PortableTokens {
  primary: string;
  secondary: string;
  accent: string;
  background: string;
  foreground: string;
  muted: string;
  border: string;
  radius: number;
  spacing: number;
  motionSpeed: number;
  fontFamily: string;
  headingScale: number;
}

export const PORTABLE_KEYS: Array<keyof PortableTokens> = [
  'primary', 'secondary', 'accent', 'background', 'foreground', 'muted', 'border',
  'radius', 'spacing', 'motionSpeed', 'fontFamily', 'headingScale',
];

const COLOR_KEYS = ['primary', 'secondary', 'accent', 'background', 'foreground', 'muted', 'border'] as const;

export const FONT_STACKS: Record<string, string> = {
  Inter: "'Inter', ui-sans-serif, system-ui, -apple-system, 'Segoe UI', sans-serif",
  'Space Grotesk': "'Space Grotesk', ui-sans-serif, system-ui, sans-serif",
  'System UI': "ui-sans-serif, system-ui, -apple-system, 'Segoe UI', Roboto, sans-serif",
  Serif: "ui-serif, Georgia, Cambria, 'Times New Roman', serif",
  Mono: "ui-monospace, SFMono-Regular, Menlo, Consolas, monospace",
};

export function fontStack(name: string): string {
  return FONT_STACKS[name] ?? FONT_STACKS.Inter;
}

/** Modular type scale: returns px sizes for h1…h4 and body from a ratio. */
export function typeScale(base: number, ratio: number) {
  const r = Math.max(1, Math.min(2, ratio || 1.25));
  return {
    body: base,
    h4: Math.round(base * r),
    h3: Math.round(base * r * r),
    h2: Math.round(base * r ** 3),
    h1: Math.round(base * r ** 4),
  };
}

function header(format: string) {
  return `Generated by The Multiverse — ${format}`;
}

export function toCssVariables(t: PortableTokens): string {
  const scale = typeScale(16, t.headingScale);
  return `/* ${header('CSS custom properties')} */
:root {
  --color-primary: ${t.primary};
  --color-primary-foreground: ${readableOn(t.primary)};
  --color-secondary: ${t.secondary};
  --color-accent: ${t.accent};
  --color-background: ${t.background};
  --color-foreground: ${t.foreground};
  --color-muted: ${t.muted};
  --color-border: ${t.border};

  --radius-sm: ${t.radius / 2}px;
  --radius-md: ${t.radius}px;
  --radius-lg: ${t.radius * 2}px;

  --space-1: ${t.spacing / 4}px;
  --space-2: ${t.spacing / 2}px;
  --space-3: ${t.spacing}px;
  --space-4: ${t.spacing * 1.5}px;
  --space-5: ${t.spacing * 2}px;
  --space-6: ${t.spacing * 3}px;

  --font-sans: ${fontStack(t.fontFamily)};
  --text-body: ${scale.body}px;
  --text-h4: ${scale.h4}px;
  --text-h3: ${scale.h3}px;
  --text-h2: ${scale.h2}px;
  --text-h1: ${scale.h1}px;

  --duration-fast: ${Math.round(150 * t.motionSpeed)}ms;
  --duration-base: ${Math.round(250 * t.motionSpeed)}ms;
  --duration-slow: ${Math.round(400 * t.motionSpeed)}ms;
}
`;
}

export function toTailwindV4(t: PortableTokens): string {
  const primary = tonalScale(t.primary);
  const scaleLines = Object.entries(primary).map(([k, v]) => `  --color-primary-${k}: ${v};`).join('\n');
  return `/* ${header('Tailwind CSS v4 @theme')} */
@import "tailwindcss";

@theme {
  --color-primary: ${t.primary};
${scaleLines}
  --color-secondary: ${t.secondary};
  --color-accent: ${t.accent};
  --color-background: ${t.background};
  --color-foreground: ${t.foreground};
  --color-muted: ${t.muted};
  --color-border: ${t.border};

  --radius-sm: ${t.radius / 2}px;
  --radius-md: ${t.radius}px;
  --radius-lg: ${t.radius * 2}px;

  --spacing: ${t.spacing / 4}px;
  --font-sans: ${fontStack(t.fontFamily)};
}
`;
}

export function toTailwindV3(t: PortableTokens): string {
  const primary = tonalScale(t.primary);
  const scale = Object.entries(primary).map(([k, v]) => `          ${k}: '${v}',`).join('\n');
  return `// ${header('Tailwind CSS v3 config')}
/** @type {import('tailwindcss').Config} */
module.exports = {
  theme: {
    extend: {
      colors: {
        primary: {
          DEFAULT: '${t.primary}',
${scale}
        },
        secondary: '${t.secondary}',
        accent: '${t.accent}',
        background: '${t.background}',
        foreground: '${t.foreground}',
        muted: '${t.muted}',
        border: '${t.border}',
      },
      borderRadius: {
        sm: '${t.radius / 2}px',
        md: '${t.radius}px',
        lg: '${t.radius * 2}px',
      },
      fontFamily: {
        sans: [${fontStack(t.fontFamily).split(',').map((f) => `"${f.trim().replace(/'/g, '')}"`).join(', ')}],
      },
    },
  },
};
`;
}

/** W3C Design Tokens Community Group format (works with Style Dictionary, Tokens Studio, Figma variables importers). */
export function toDtcgJson(t: PortableTokens): string {
  const color: Record<string, { $type: 'color'; $value: string }> = {};
  for (const key of COLOR_KEYS) color[key] = { $type: 'color', $value: t[key] };
  const scale = typeScale(16, t.headingScale);
  const doc = {
    $description: header('W3C Design Tokens (DTCG)'),
    color,
    radius: {
      sm: { $type: 'dimension', $value: `${t.radius / 2}px` },
      md: { $type: 'dimension', $value: `${t.radius}px` },
      lg: { $type: 'dimension', $value: `${t.radius * 2}px` },
    },
    spacing: {
      base: { $type: 'dimension', $value: `${t.spacing}px` },
    },
    font: {
      family: { $type: 'fontFamily', $value: fontStack(t.fontFamily) },
      size: Object.fromEntries(Object.entries(scale).map(([k, v]) => [k, { $type: 'dimension', $value: `${v}px` }])),
    },
    duration: {
      base: { $type: 'duration', $value: `${Math.round(250 * t.motionSpeed)}ms` },
    },
  };
  return JSON.stringify(doc, null, 2) + '\n';
}

export function toScss(t: PortableTokens): string {
  return `// ${header('SCSS variables')}
$color-primary: ${t.primary};
$color-secondary: ${t.secondary};
$color-accent: ${t.accent};
$color-background: ${t.background};
$color-foreground: ${t.foreground};
$color-muted: ${t.muted};
$color-border: ${t.border};

$radius-sm: ${t.radius / 2}px;
$radius-md: ${t.radius}px;
$radius-lg: ${t.radius * 2}px;

$space-base: ${t.spacing}px;
$font-sans: ${fontStack(t.fontFamily)};
$duration-base: ${Math.round(250 * t.motionSpeed)}ms;
`;
}

export type ExportFormat = 'css' | 'tailwind4' | 'tailwind3' | 'dtcg' | 'scss';

export const EXPORT_FORMATS: Array<{ id: ExportFormat; label: string; filename: string; mime: string; build: (t: PortableTokens) => string }> = [
  { id: 'css', label: 'CSS Variables', filename: 'tokens.css', mime: 'text/css', build: toCssVariables },
  { id: 'tailwind4', label: 'Tailwind v4', filename: 'theme.css', mime: 'text/css', build: toTailwindV4 },
  { id: 'tailwind3', label: 'Tailwind v3', filename: 'tailwind.config.js', mime: 'text/javascript', build: toTailwindV3 },
  { id: 'dtcg', label: 'Design Tokens (JSON)', filename: 'tokens.json', mime: 'application/json', build: toDtcgJson },
  { id: 'scss', label: 'SCSS', filename: '_tokens.scss', mime: 'text/x-scss', build: toScss },
];

// ---------------------------------------------------------------------------
// Share links — tokens are encoded in the URL hash so nothing leaves the browser.
// ---------------------------------------------------------------------------

function toBase64Url(input: string): string {
  const bytes = new TextEncoder().encode(input);
  let binary = '';
  bytes.forEach((b) => { binary += String.fromCharCode(b); });
  return btoa(binary).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
}

function fromBase64Url(input: string): string {
  const padded = input.replace(/-/g, '+').replace(/_/g, '/') + '==='.slice((input.length + 3) % 4);
  const binary = atob(padded);
  const bytes = Uint8Array.from(binary, (c) => c.charCodeAt(0));
  return new TextDecoder().decode(bytes);
}

export function encodeTokens(t: PortableTokens): string {
  const picked: Record<string, unknown> = {};
  for (const key of PORTABLE_KEYS) picked[key] = t[key];
  return toBase64Url(JSON.stringify({ v: 1, t: picked }));
}

/**
 * Decodes and validates a shared token payload. Unknown keys are dropped and
 * every value is type- and range-checked, so a crafted link can never inject
 * arbitrary CSS or state.
 */
export function decodeTokens(payload: string): Partial<PortableTokens> | null {
  try {
    const parsed = JSON.parse(fromBase64Url(payload)) as { v?: number; t?: Record<string, unknown> };
    if (!parsed || parsed.v !== 1 || typeof parsed.t !== 'object' || parsed.t === null) return null;
    return sanitizeTokens(parsed.t);
  } catch {
    return null;
  }
}

export function sanitizeTokens(input: Record<string, unknown>): Partial<PortableTokens> {
  const out: Partial<PortableTokens> = {};
  for (const key of COLOR_KEYS) {
    const v = input[key];
    if (typeof v === 'string') {
      const hex = normalizeHex(v);
      if (hex) out[key] = hex;
    }
  }
  const num = (v: unknown, min: number, max: number) =>
    typeof v === 'number' && Number.isFinite(v) ? Math.min(max, Math.max(min, v)) : undefined;
  const radius = num(input.radius, 0, 48);
  const spacing = num(input.spacing, 4, 48);
  const motionSpeed = num(input.motionSpeed, 0.1, 3);
  const headingScale = num(input.headingScale, 1, 2);
  if (radius !== undefined) out.radius = radius;
  if (spacing !== undefined) out.spacing = spacing;
  if (motionSpeed !== undefined) out.motionSpeed = motionSpeed;
  if (headingScale !== undefined) out.headingScale = headingScale;
  if (typeof input.fontFamily === 'string' && input.fontFamily in FONT_STACKS) out.fontFamily = input.fontFamily;
  return out;
}
